// Builds one redirect page per entry in links.json: jipraks.id/<slug> -> target URL.
// GitHub Pages cannot send server redirects, so each page redirects in the browser.
// Run: node scripts/build-links.mjs
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync, rmSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const MARKER = "<!-- generated by scripts/build-links.mjs -->";
const RESERVED = new Set(["scripts", "assets", ".git", ".claude"]);

const links = JSON.parse(readFileSync(join(root, "links.json"), "utf8"));

const escapeAttr = (s) =>
  s.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

function page(url) {
  const attr = escapeAttr(url);
  return `<!doctype html>
${MARKER}
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="robots" content="noindex">
  <title>Redirecting</title>
  <meta http-equiv="refresh" content="0; url=${attr}">
  <link rel="canonical" href="${attr}">
  <script>location.replace(${JSON.stringify(url)});</script>
</head>
<body>
  <p><a href="${attr}">Continue / Lanjutkan</a></p>
</body>
</html>
`;
}

let errors = 0;
for (const [slug, url] of Object.entries(links)) {
  if (!/^[a-z0-9][a-z0-9-]*$/.test(slug) || RESERVED.has(slug)) {
    console.error(`skip "${slug}": use lowercase letters, numbers and dashes, and not a reserved name`);
    errors++;
    continue;
  }
  if (!/^https?:\/\//.test(url)) {
    console.error(`skip "${slug}": target must start with http:// or https://`);
    errors++;
    continue;
  }
  const dir = join(root, slug);
  const file = join(dir, "index.html");
  if (existsSync(file) && !readFileSync(file, "utf8").includes(MARKER)) {
    console.error(`skip "${slug}": ${slug}/index.html exists and was not made by this script`);
    errors++;
    continue;
  }
  mkdirSync(dir, { recursive: true });
  writeFileSync(file, page(url));
  console.log(`/${slug} -> ${url}`);
}

// Remove pages this script made earlier for slugs no longer in links.json.
for (const entry of readdirSync(root, { withFileTypes: true })) {
  if (!entry.isDirectory() || entry.name in links) continue;
  const file = join(root, entry.name, "index.html");
  if (existsSync(file) && readFileSync(file, "utf8").includes(MARKER)) {
    rmSync(file);
    const dir = join(root, entry.name);
    if (readdirSync(dir).length === 0) rmSync(dir, { recursive: true });
    console.log(`removed /${entry.name}`);
  }
}

process.exitCode = errors ? 1 : 0;
